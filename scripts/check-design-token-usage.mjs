const nonLiteralFixture = [
  '// const ignored = `#123456`',
  '/* rgb(1 2 3) */',
  'const numeric = 0x123456',
  'const matcher = /#123456/',
].join('\n')
if (lintSource('fixtures/non-literal-colors.ts', nonLiteralFixture).length !== 0) {
  console.error('Design token usage check failed: comments, numbers, and regular expressions must not be treated as color literals.')
  process.exit(1)
}

const scanTargets = [
  'packages/ui/src',
  'packages/app/src',
  'packages/app/browser.html',
  'packages/app/chart-frame.html',
  'apps/desktop/public',
  'apps/desktop/index.html',
  'apps/desktop/chart-frame.html',
  'apps/desktop/loading.html',
  'apps/desktop/src/main/startup-splash.ts',
  'apps/desktop/src/main/main-window-controller.ts',
]

const files = new Set(scanTargets.flatMap((target) => sourceFiles(join(root, target))))
const errors = validateAllowlist()
for (const path of files) {
  const relPath = portable(relative(root, path))
  errors.push(...lintSource(relPath, readFileSync(path, 'utf8')))
}

if (errors.length > 0) {
  console.error(`Design token usage check failed:\n${errors.map((entry) => `- ${entry}`).join('\n')}`)
  process.exit(1)
}

process.stdout.write(
  `Design token usage check passed (${files.size} renderer/startup assets; zero raw chrome colors; `
  + `${rawColorAllowlist.size} exact artwork palettes; 1 exact generated token artifact).\n`,
)
