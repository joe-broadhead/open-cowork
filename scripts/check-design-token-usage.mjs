function validateAllowlist() {
  const errors = []
  for (const [relPath, reason] of rawColorAllowlist) {
    const path = join(root, relPath)
    if (!reason.trim()) errors.push(`${relPath}: artwork allowlist entry is missing its reason.`)
    if (!existsSync(path) || !statSync(path).isFile()) {
      errors.push(`${relPath}: artwork allowlist path does not exist; remove the stale exception.`)
      continue
    }
    const source = readFileSync(path, 'utf8')
    if (!containsRawColor(source)) errors.push(`${relPath}: artwork allowlist is no longer needed; remove the stale exception.`)
  }

  const generatedPath = join(root, generatedTokenException.relPath)
  const generatedSourcePath = join(root, generatedTokenException.sourceRelPath)
  if (!generatedTokenException.reason.trim()) {
    errors.push(`${generatedTokenException.relPath}: generated token exception is missing its reason.`)
  }
  if (!existsSync(generatedSourcePath) || !statSync(generatedSourcePath).isFile()) {
    errors.push(
      `${generatedTokenException.relPath}: token source ${generatedTokenException.sourceRelPath} is missing; remove the stale exception.`,
    )
  }
  if (!existsSync(generatedPath) || !statSync(generatedPath).isFile()) {
    errors.push(`${generatedTokenException.relPath}: generated token exception path does not exist; remove the stale exception.`)
  } else {
    const generatedSource = readFileSync(generatedPath, 'utf8')
    if (!generatedSource.startsWith(`${generatedTokenException.expectedHeader}\n`)) {
      errors.push(`${generatedTokenException.relPath}: generated token exception lost its source-of-truth header.`)
    }
    if (!containsRawColor(generatedSource)) {
      errors.push(`${generatedTokenException.relPath}: generated token exception is no longer needed; remove it.`)
    }
  }
  return errors
}

const fixtureViolations = lintSource(
  'fixtures/raw-startup-color.css',
  '.fixture { color: #123456; background: rgb(1 2 3 / 50%); }',
)
if (
  fixtureViolations.length !== 2
  || !fixtureViolations.every((violation) => violation.startsWith('fixtures/raw-startup-color.css:1'))
) {
  console.error('Design token usage check failed: the raw-color fixture did not fail with file-and-line diagnostics.')
  process.exit(1)
}

