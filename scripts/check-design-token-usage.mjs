// Semantic-color guard for renderer components and every startup asset.
//
// Raw palette values belong in the shared token source. Product chrome must
// consume `var(--color-*)` / `color-mix(...)`. The only exceptions are exact,
// reviewed artwork/data palettes and the generated token distribution artifact
// whose paths and reasons are recorded below.

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { extname, join, relative } from 'node:path'

const root = process.cwd()
const scannedExtensions = new Set(['.css', '.html', '.js', '.jsx', '.ts', '.tsx'])
const codeExtensions = new Set(['.js', '.jsx', '.ts', '.tsx'])
const validHexLengths = new Set([3, 4, 6, 8])
const ignoredPathSegments = new Set(['dist', 'node_modules'])

// Exact artwork/data-palette exceptions. A broad directory or unexplained file
// is intentionally invalid: every exception must earn its place.
const rawColorAllowlist = new Map([
  [
    'packages/ui/src/knowledge-hues.ts',
    'Categorical Knowledge-space identity palette; values identify data entities rather than product chrome.',
  ],
  [
    'packages/ui/src/utils.ts',
    'Categorical entity-identity hue ring; values identify user content rather than product chrome.',
  ],
  [
    'packages/app/src/components/plugins/PluginIcon.tsx',
    'Third-party provider and file-type logo artwork must retain the owners\' published brand colors.',
  ],
  [
    'packages/app/src/styles/domains/code-syntax-palette.css',
    'Highlight.js categorical syntax palette colors code tokens and is isolated from product chrome.',
  ],
])

const generatedTokenException = {
  relPath: 'packages/app/src/styles/generated/design-tokens.css',
  sourceRelPath: 'packages/shared/src/design-tokens.ts',
  expectedHeader: '/* Generated by scripts/generate-design-token-css.ts from packages/shared/src/design-tokens.ts. Do not edit. */',
  reason: 'Generated semantic-token distribution; pnpm design-tokens:check verifies it matches the shared token source.',
}

const hexPattern = /#[0-9a-fA-F]{3,8}\b/g
const functionalColorPattern = /\b(?:rgba?|hsla?)\s*\(/g

function containsRawColor(source) {
  const hasRawColor = [...source.matchAll(hexPattern)].some((match) => (
    validHexLengths.has(match[0].length - 1)
  )) || functionalColorPattern.test(source)
  functionalColorPattern.lastIndex = 0
  return hasRawColor
}

function portable(path) {
  return path.split('\\').join('/')
}

function codeStringLiteralMask(source) {
  const mask = new Uint8Array(source.length)
  const templateExpressionDepth = []
  let mode = 'code'
  let escaped = false

  for (let index = 0; index < source.length; index += 1) {
    const character = source[index]
    const next = source[index + 1]

    if (mode === 'line-comment') {
      if (character === '\n') mode = 'code'
      continue
    }
    if (mode === 'block-comment') {
      if (character === '*' && next === '/') {
        mode = 'code'
        index += 1
      }
      continue
    }
    if (mode === 'single' || mode === 'double') {
      mask[index] = 1
      if (escaped) escaped = false
      else if (character === '\\') escaped = true
      else if ((mode === 'single' && character === "'") || (mode === 'double' && character === '"')) mode = 'code'
      continue
    }
    if (mode === 'template') {
      mask[index] = 1
      if (escaped) {
        escaped = false
        continue
      }
      if (character === '\\') {
        escaped = true
        continue
      }
      if (character === '`') {
        mode = 'code'
        continue
      }
      if (character === '$' && next === '{') {
        mask[index + 1] = 1
        templateExpressionDepth.push(1)
        mode = 'code'
        index += 1
      }
      continue
    }

    if (character === '/' && next === '/') {
      mode = 'line-comment'
      index += 1
      continue
    }
    if (character === '/' && next === '*') {
      mode = 'block-comment'
      index += 1
      continue
    }
    if (character === "'") {
      mode = 'single'
      mask[index] = 1
      continue
    }
    if (character === '"') {
      mode = 'double'
      mask[index] = 1
      continue
    }
    if (character === '`') {
      mode = 'template'
      mask[index] = 1
      continue
    }
    if (templateExpressionDepth.length === 0) continue
    if (character === '{') templateExpressionDepth[templateExpressionDepth.length - 1] += 1
    else if (character === '}') {
      templateExpressionDepth[templateExpressionDepth.length - 1] -= 1
      if (templateExpressionDepth[templateExpressionDepth.length - 1] === 0) {
        templateExpressionDepth.pop()
        mode = 'template'
      }
    }
  }

  return mask
}

function lineNumberAt(source, index) {
  let line = 1
  for (let cursor = 0; cursor < index; cursor += 1) {
    if (source[cursor] === '\n') line += 1
  }
  return line
}

function lintSource(relPath, source) {
  if (rawColorAllowlist.has(relPath) || relPath === generatedTokenException.relPath) return []
  const extension = extname(relPath)
  const requireStringContext = codeExtensions.has(extension)
  const stringLiteralMask = requireStringContext ? codeStringLiteralMask(source) : null
  const violations = []

  for (const match of source.matchAll(hexPattern)) {
    const literal = match[0]
    if (!validHexLengths.has(literal.length - 1)) continue
    if (requireStringContext && !stringLiteralMask[match.index]) continue
    violations.push(
      `${relPath}:${lineNumberAt(source, match.index)} raw hex color literal "${literal}" — use a semantic token `
      + '(var(--color-*) / color-mix) or add an exact artwork allowlist entry with a reason.',
    )
  }

  for (const match of source.matchAll(functionalColorPattern)) {
    if (requireStringContext && !stringLiteralMask[match.index]) continue
    violations.push(
      `${relPath}:${lineNumberAt(source, match.index)} raw ${match[0].replace(/\s*\($/, '')}() color literal — use a semantic token `
      + '(var(--color-*) / color-mix) or add an exact artwork allowlist entry with a reason.',
    )
  }

  return violations
}

function shouldIgnore(path) {
  const relPath = portable(relative(root, path))
  const segments = relPath.split('/')
  if (segments.some((segment) => ignoredPathSegments.has(segment))) return true
  return /\.(?:test|spec)\.(?:js|jsx|ts|tsx)$/.test(relPath)
}

function sourceFiles(path) {
  if (!existsSync(path)) return []
  const stats = statSync(path)
  if (stats.isFile()) return scannedExtensions.has(extname(path)) ? [path] : []
  if (!stats.isDirectory()) return []

  return readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
    const child = join(path, entry.name)
    if (shouldIgnore(child)) return []
    return sourceFiles(child)
  })
}

const generatedProductFixturePath = join(
  root,
  'tests/fixtures/design-token-usage/src/generated/product.css',
)
const generatedProductFixtureRelPath = portable(relative(root, generatedProductFixturePath))
const generatedProductFixtureFiles = sourceFiles(join(root, 'tests/fixtures/design-token-usage/src'))
const generatedProductFixtureViolations = generatedProductFixtureFiles.includes(generatedProductFixturePath)
  ? lintSource(generatedProductFixtureRelPath, readFileSync(generatedProductFixturePath, 'utf8'))
  : []
if (
  !generatedProductFixtureFiles.includes(generatedProductFixturePath)
  || generatedProductFixtureViolations.length !== 1
  || !generatedProductFixtureViolations[0].startsWith(`${generatedProductFixtureRelPath}:2`)
) {
  console.error('Design token usage check failed: src/generated product fixture was not scanned with file-and-line diagnostics.')
  process.exit(1)
}

